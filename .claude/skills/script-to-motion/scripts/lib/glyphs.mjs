/**
 * glyphs.mjs — checks for type that is not DOM text: glyph outlines (js/glyphs.js, made by text_to_paths.mjs) and
 * text drawn on canvases by TypeFX (TX.raster). Both must come from installed SIL OFL 1.1 catalogue fonts, like
 * every other glyph in the video (SKILL.md → Fonts).
 * Used by check.mjs (static: provenance of js/glyphs.js) and check_fonts.mjs (runtime: canvas text coverage).
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { loadCatalog, allowedFonts } from './fonts.mjs';
import { REQUIRED_LICENSE } from './fontfetch.mjs';

/** provenance of js/glyphs.js: every entry from a catalogue OFL font file installed unmodified; glyphs.json in sync */
export function auditGlyphs(dir, catalog = loadCatalog()) {
  const errors = [], warnings = [];
  const html = fs.existsSync(path.join(dir, 'index.html')) ? fs.readFileSync(path.join(dir, 'index.html'), 'utf8').replace(/<!--[\s\S]*?-->/g, '') : '';
  const loads = /src=["']js\/glyphs\.js["']/.test(html);
  const file = path.join(dir, 'js', 'glyphs.js');
  const specFile = path.join(dir, 'glyphs.json');
  if (!loads && !fs.existsSync(file)) return { errors, warnings, entries: {} };
  if (!fs.existsSync(file)) { errors.push('index.html loads js/glyphs.js but it does not exist — run text_to_paths.mjs'); return { errors, warnings, entries: {} }; }
  if (!loads) warnings.push('js/glyphs.js exists but index.html does not load it (add <script src="js/glyphs.js"> before js/typefx.js)');
  let entries = {};
  try {
    const ctx = { window: {} };
    vm.runInNewContext(fs.readFileSync(file, 'utf8'), ctx, { filename: 'glyphs.js' });
    entries = ctx.window.GLYPHS || {};
  } catch (e) { errors.push(`js/glyphs.js does not evaluate: ${e.message}`); return { errors, warnings, entries: {} }; }
  if (!/generated by text_to_paths\.mjs/.test(fs.readFileSync(file, 'utf8').slice(0, 300))) {
    errors.push('js/glyphs.js was not generated by text_to_paths.mjs — outlines must come from catalogue fonts through the tool (it verifies the font file and licence)');
  }
  let total = 0;
  const ALLOWED = allowedFonts(dir, catalog).fonts;
  for (const [key, e] of Object.entries(entries)) {
    const f = e.font || {};
    const cat = ALLOWED.find((x) => x.id === f.id);
    if (!cat) { errors.push(`glyphs "${key}": font "${f.id}" is neither a catalogue font nor installed from Google Fonts (fonts.lock.json)`); continue; }
    if (cat.license !== REQUIRED_LICENSE || f.license !== REQUIRED_LICENSE) errors.push(`glyphs "${key}": font ${f.id} is not SIL OFL 1.1`);
    const known = new Set(cat.files.map((x) => x.sha256));
    for (const rec of [{ file: f.file, sha256: f.sha256 }, ...(e.files || [])]) {
      if (!known.has(rec.sha256)) errors.push(`glyphs "${key}": outlines were made from ${rec.file} with sha256 ${String(rec.sha256).slice(0, 12)}… — not the unmodified installed file`);
      if (!fs.existsSync(path.join(dir, rec.file))) errors.push(`glyphs "${key}": ${rec.file} is not installed in the project (fonts and their licences travel with the outlines) — add_font.mjs ${f.id}`);
    }
    if (!fs.existsSync(path.join(dir, cat.licenseFile.dest))) errors.push(`glyphs "${key}": licence file ${cat.licenseFile.dest} missing`);
    total += (e.glyphs || []).length;
  }
  if (total > 300) warnings.push(`js/glyphs.js holds ${total} glyph outlines — outlines are for display lines; keep body text as real text`);
  if (fs.existsSync(specFile)) {
    try {
      const spec = JSON.parse(fs.readFileSync(specFile, 'utf8'));
      const a = Object.keys(spec).sort().join(','), b = Object.keys(entries).sort().join(',');
      const stale = Object.keys(spec).filter((k) => !entries[k] || entries[k].text !== spec[k].text || ![entries[k].font.id, String(entries[k].font.family).toLowerCase()].includes(String(spec[k].font).toLowerCase()) || entries[k].size !== (spec[k].size || 200));
      if (a !== b || stale.length) warnings.push(`glyphs.json changed since js/glyphs.js was built${stale.length ? ` (${stale.join(', ')})` : ''} — run text_to_paths.mjs`);
    } catch (e) { errors.push(`glyphs.json: ${e.message}`); }
  }
  return { errors: [...new Set(errors)], warnings, entries };
}

/** family names of a CSS font shorthand or family list: "800 160px 'Pretendard', sans-serif" → ['Pretendard', 'sans-serif'] */
export function familiesOf(fontOrFamily) {
  const s = String(fontOrFamily || '');
  const m = s.match(/\d+(?:\.\d+)?px(?:\s*\/\s*[\d.]+\w*)?\s+(.+)$/);
  return (m ? m[1] : s).split(',').map((x) => x.trim().replace(/^['"]|['"]$/g, '')).filter(Boolean);
}

const GENERIC_FAMILY = /^(serif|sans-serif|monospace|cursive|fantasy|system-ui|ui-serif|ui-sans-serif|ui-monospace|ui-rounded|emoji|math|fangsong)$/i;

/**
 * Canvas text (every fillText/strokeText the page drew, from fontHooks in lib/fonts.mjs): the FIRST family of its font
 * must be an installed one — a generic family first ("48px sans-serif, 'Pretendard'") always matches, so a system font
 * draws everything — and the installed families must cover every character. Returns { fails, notes }.
 */
export async function canvasTextProblems(dir, canvasText, families, catalog = loadCatalog()) {
  const fails = [], notes = [];
  const byFont = new Map();
  for (const { font, text } of canvasText) {
    const e = byFont.get(font) || { chars: new Set(), sample: text };
    for (const ch of text) if (ch.trim()) e.chars.add(ch);
    byFont.set(font, e);
  }
  for (const [font, e] of byFont) {
    if (!e.chars.size) continue;
    const fams = familiesOf(font);
    const first = fams[0];
    const sample = e.sample.slice(0, 30);
    if (!first || !families.has(first.toLowerCase())) {
      const why = !first ? 'no font named (the canvas default is a system font)'
        : GENERIC_FAMILY.test(first) ? `it starts with the generic "${first}", which always matches — a system font draws it${fams.length > 1 ? ` and ${fams.slice(1).map((f) => `"${f}"`).join(', ')} never does` : ''}`
          : `"${first}" is not an installed catalogue font`;
      fails.push(`canvas text "${sample}" is drawn in "${font}" — ${why}: set ctx.font = "<size>px 'Pretendard', sans-serif" (an installed SIL OFL 1.1 family first)`);
      continue;
    }
    const cov = await uncovered(dir, fams, [...e.chars].join(''), catalog);
    if (cov.skipped) { fails.push(`canvas text in "${font}" could not be checked (${cov.skipped}) — npm install in the skill's scripts folder`); continue; }
    if (cov.missing.length) fails.push(`canvas text "${sample}" (${font}): no installed font has ${cov.missing.map((c) => JSON.stringify(c)).join(' ')} — the canvas would draw them with a system font`);
  }
  if (byFont.size) notes.push(`canvas text: ${byFont.size} font setting(s) checked character by character`);
  return { fails, notes };
}

/**
 * characters of `text` that no installed catalogue family in `families` (in order) can draw — those would fall
 * back to a system font on a canvas. Needs fontkit (installed with the skill's scripts).
 */
export async function uncovered(dir, families, text, catalog = loadCatalog()) {
  let fontkit;
  try { fontkit = await import('fontkit'); } catch { return { missing: [], skipped: 'fontkit not installed' }; }
  const faces = [];
  const unknown = [];
  const ALLOWED = allowedFonts(dir, catalog).fonts;
  for (const fam of families) {
    if (/^(serif|sans-serif|monospace|cursive|fantasy|system-ui|emoji)$/i.test(fam)) continue;
    const cat = ALLOWED.find((x) => x.family.toLowerCase() === fam.toLowerCase());
    if (!cat) { unknown.push(fam); continue; }
    for (const f of cat.files) {
      const abs = path.join(dir, f.dest);
      if (!fs.existsSync(abs)) continue;
      try { faces.push(fontkit.openSync(abs)); } catch { /* unreadable: treated as not covering */ }
    }
  }
  const missing = [];
  for (const ch of new Set([...String(text)].filter((c) => c.trim()))) {
    if (!faces.some((fc) => { try { return fc.hasGlyphForCodePoint(ch.codePointAt(0)); } catch { return false; } })) missing.push(ch);
  }
  return { missing, unknown };
}
