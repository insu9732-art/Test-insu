#!/usr/bin/env node
/**
 * sync.mjs — phrase times for cue(id).when('phrase'), as the agent set them. Writes <project>/js/sync.js.
 *
 *   node sync.mjs <projectDir>            (after tts.mjs; again after a cut, a re-take or a changed "at")
 *
 * Nothing is measured here, and no code decides where a word, a pause or a silence is. The agent reads a take's levels
 * with `node wave.mjs <dir> --cue <id> [--step 0.01]` and writes in script.json, for each phrase the scenes anchor with
 * when(), the second in the take as recorded at which its first syllable starts (references/sound.md §2):
 *   { "id": "c05", "say": "…", "at": { "take": "<the take's id>", "phrases": { "천억": 1.35, "영상 그 자체": 3.02 } } }
 * The phrase is written as it appears in the cue's text (what when() looks up). sync.mjs only moves each time back by the
 * stretches the cue's "cut" took out before it (lib/phrases.mjs) and writes SYNC[id] = { take, d, phrases } — seconds from
 * the cue's start. An "at" set on another take is left out and reported: read the new take and set it again.
 *
 * when() returns the set time for those phrases. For any other phrase, and for placeholder cues (not recorded yet), it
 * estimates by character position; for a recorded cue the player says so once in the console (errscan.mjs reports it).
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { phraseTimes } from './lib/phrases.mjs';

const ROOT = path.resolve(process.argv[2] || '.');
const die = (m, code = 2) => { console.error('✖ ' + m); process.exit(code); };
if (!fs.existsSync(path.join(ROOT, 'js/cues.js'))) die(`no js/cues.js in ${ROOT} — run tts.mjs first`);
let script;
try { script = JSON.parse(fs.readFileSync(path.join(ROOT, 'script.json'), 'utf8')); } catch (e) { die(`script.json: ${e.message}`); }
const box = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'js/cues.js'), 'utf8'), box);
const DATA = box.window.VIDEO_DATA;
const byId = new Map(DATA.cues.map((c) => [c.id, c]));

const takeLen = (c) => {
  const f = c && c.take ? path.join(ROOT, '.tts-cache', `${c.take}.pcm`) : null;
  return f && fs.existsSync(f) ? fs.statSync(f).size / 2 / 44100 : null;   // (tts.mjs keeps takes as 16-bit mono 44.1 kHz)
};

const SYNC = {}, problems = [], stale = [];
let nPhrases = 0;
for (const sc of script.cues || []) {
  if (sc.at == null) continue;
  const c = byId.get(sc.id);
  if (!c) { problems.push(`${sc.id}: not in js/cues.js — run tts.mjs first`); continue; }
  const r = phraseTimes(sc, c, takeLen(c));
  if (r.problems) { for (const p of r.problems) problems.push(`${sc.id}: ${p}`); continue; }
  if (r.stale) { stale.push(`${sc.id} (${r.stale})`); continue; }
  SYNC[sc.id] = { take: c.take, d: c.duration, phrases: r.phrases };
  nPhrases += Object.keys(r.phrases).length;
}
if (problems.length) die(`script.json "at":\n  ${problems.join('\n  ')}\nNothing was written.`, 1);

fs.writeFileSync(path.join(ROOT, 'js/sync.js'),
  `// Generated by sync.mjs from script.json "at" (the phrase times the agent set) — edit those and re-run. Do not edit.
// SYNC[id].phrases[phrase]: seconds after the cue start at which the phrase's first syllable starts.
window.SYNC = ${JSON.stringify(SYNC)};
`);
const recorded = DATA.cues.filter((c) => c.take);
const without = recorded.filter((c) => !SYNC[c.id]).map((c) => c.id);
console.log(`js/sync.js: ${nPhrases} phrase time(s) in ${Object.keys(SYNC).length} cue(s)` +
  (without.length ? ` · ${without.length} recorded cue(s) have none — their when() phrases are estimated: ${without.join(', ')}` : ''));
if (stale.length) console.log(`⚠ not used — "at" set on another take: ${stale.join(', ')}. Read the take now in js/cues.js (node wave.mjs <dir> --cue <id>) and set "at" again.`);
