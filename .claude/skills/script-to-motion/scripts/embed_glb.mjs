#!/usr/bin/env node
/**
 * embed_glb.mjs — make a .glb loadable from file:// by embedding it in a script.
 *
 *   node embed_glb.mjs <file.glb> <projectDir> [--name mug]
 *
 * Copies the GLB to <project>/models/<name>.glb (the source asset, kept for reuse) and writes
 * <project>/models/<name>.glb.js:  (window.GLB_ASSETS ||= {})["name"] = "<base64>";
 * then adds <script src="models/<name>.glb.js"> to index.html before js/scenes.js (once).
 * Load it in scenes.js with `await Stage3D.loadGLB('name')` (FX build: `StageFX.loadGLB`). Browsers block fetch() of local files,
 * which is why the model travels inside a script.
 *
 * The .glb must be in the project and be either made here — written by a Blender run of blender_mcp.mjs, recorded in
 * generated.json unchanged — or the user's, declared in provenance.json. Anything else is refused (SKILL.md →
 * Originality). Both written files are recorded in generated.json.
 */
import fs from 'node:fs';
import path from 'node:path';
import { projectOf, readRecord, recordGenerated, sha256File } from './lib/generated.mjs';

const argv = process.argv.slice(2);
const pos = argv.filter((a, i) => !a.startsWith('--') && argv[i - 1] !== '--name');
const nameArg = argv.includes('--name') ? argv[argv.indexOf('--name') + 1] : null;
const [glbPath, projectDir] = pos;
if (!glbPath || !projectDir) {
  console.error('usage: node embed_glb.mjs <file.glb> <projectDir> [--name mug]');
  process.exit(2);
}
const buf = fs.readFileSync(glbPath);
if (buf.toString('ascii', 0, 4) !== 'glTF') { console.error(`✖ ${glbPath} is not a binary glTF (.glb)`); process.exit(1); }
const name = (nameArg || path.basename(glbPath, '.glb')).replace(/[^A-Za-z0-9_-]/g, '_');
const dir = path.resolve(projectDir);
// where the model came from: made here (generated.json) or given by the user (provenance.json) — nothing else
{
  const src = path.resolve(glbPath);
  const root = projectOf(dir);
  if (!root) { console.error(`✖ ${dir} is not a video project (no index.html and script.json)`); process.exit(2); }
  if (projectOf(src) !== root) { console.error(`✖ ${glbPath} is not in the project ${dir} — build the model with a Blender script in assets3d/ (blender_mcp.mjs run), or put the user's file in assets/user/ and declare it in provenance.json`); process.exit(1); }
  const rel = path.relative(root, src).split(path.sep).join('/');
  let made = false, given = false;
  try { const e = readRecord(root).files[rel]; made = !!e && e.sha256 === sha256File(src); } catch (e) { console.error(`✖ generated.json: ${e.message}`); process.exit(1); }
  try {
    const prov = fs.existsSync(path.join(root, 'provenance.json')) ? JSON.parse(fs.readFileSync(path.join(root, 'provenance.json'), 'utf8')) : { assets: [] };
    given = (prov.assets || []).some((a) => a && a.source === 'user' && path.resolve(root, String(a.file || '')) === src);
  } catch (e) { console.error(`✖ provenance.json: ${e.message}`); process.exit(1); }
  if (!made && !given) { console.error(`✖ ${rel} was not made by a Blender run here (no unchanged entry in generated.json) and is not declared as the user's in provenance.json — refused. Build it with blender_mcp.mjs run assets3d/<name>.py (the run records what Blender writes), or declare the user's file`); process.exit(1); }
}
const models = path.join(dir, 'models');
fs.mkdirSync(models, { recursive: true });
if (path.resolve(glbPath) !== path.join(models, `${name}.glb`)) fs.copyFileSync(glbPath, path.join(models, `${name}.glb`));
fs.writeFileSync(path.join(models, `${name}.glb.js`),
  `// Generated by embed_glb.mjs from ${name}.glb (${(buf.length / 1024).toFixed(0)} KB) — base64 so it loads from file://.\n` +
  `(window.GLB_ASSETS = window.GLB_ASSETS || {})[${JSON.stringify(name)}] = "${buf.toString('base64')}";\n`);
recordGenerated([path.join(models, `${name}.glb`), path.join(models, `${name}.glb.js`)], 'embed_glb.mjs');

const indexPath = path.join(dir, 'index.html');
let html = fs.readFileSync(indexPath, 'utf8');
const tag = `<script src="models/${name}.glb.js"></script>`;
if (!html.includes(tag)) {
  if (!html.includes('<script src="js/scenes.js"></script>')) { console.error('✖ index.html has no <script src="js/scenes.js"> to insert before'); process.exit(1); }
  html = html.replace('<script src="js/scenes.js"></script>', `${tag}\n  <script src="js/scenes.js"></script>`);
  fs.writeFileSync(indexPath, html);
}
// either build loads it: the classic one (stage3d.js → Stage3D) or the FX one (stagefx.js → StageFX)
const fx = html.includes('vendor/three/stagefx.js'), classic = html.includes('vendor/three/stage3d.js');
if (!fx && !classic) {
  console.warn(`⚠ three.js is not enabled in this project yet: node ${path.join(path.dirname(process.argv[1]), 'enable_3d.mjs')} ${projectDir}` +
    ' (classic build) — or add --fx for the shader-FX build (bloom, light rays, depth of field…; references/shader-fx.md). One build per project.');
}
console.log(`✓ models/${name}.glb.js (${(buf.length / 1024).toFixed(0)} KB) — load with await ${fx ? 'StageFX' : 'Stage3D'}.loadGLB(${JSON.stringify(name)})`);
