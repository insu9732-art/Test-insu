export const DREAM_CATEGORIES = ['동물', '사람', '신체', '자연', '물건·장소', '행동·상황'];

export const DREAMS = RAW.map(([category, keys, luck, text]) => ({
  category,
  keys: keys.split(','),
  title: keys.split(',')[0],
  luck,
  text,
}));

export function searchDreams(query, category) {
  const q = (query || '').replace(/\s+/g, '').replace(/꿈$/, '');
  return DREAMS.filter((d) => {
    if (category && d.category !== category) return false;
    if (!q) return true;
    return d.keys.some((k) => k.includes(q) || (k.length > 1 && q.includes(k))) || (q.length > 1 && d.text.includes(q));
  });
}
